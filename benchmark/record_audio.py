#!/usr/bin/env python3
"""Record the benchmark utterances, one turn at a time.

Shows the line to read, records it, saves <turn_id>.wav, and moves to the next
turn. One button: it says Record, and while recording it says Stop.

Also writes benchmark/audio/manifest.json after every take -- a benchmark-shaped
file holding only the turns you have actually recorded, with the map, position,
grading notes and reference utterance carried over. The test runner consumes it
directly, so there is no separate bookkeeping step:

    python run_parity_benchmark.py --benchmark benchmark/audio/manifest.json \
        --audio-dir benchmark/audio --formatter curated

    python3 record_audio.py
    python3 record_audio.py --server http://localhost:11435   # hear-check takes

Capture goes through speech_recognition with the same settings mapio uses
(TIMEOUT, PHRASE_TIME_LIMIT, FINAL_SILENCE_DURATION) and is written as 16 kHz
mono 16-bit PCM, so a recording here is byte-for-byte what mapio would POST.

Run it under the Python that owns the microphone -- Windows-native, not WSL. See
benchmark/audio/README.md.
"""

import argparse
import base64
import json
import os
import threading
import tkinter as tk
import urllib.request
import wave
from datetime import datetime
from tkinter import font as tkfont
from tkinter import messagebox, ttk

import speech_recognition as sr

# Same numbers as src/view/audio/stt.py, duplicated rather than imported so this
# script runs without the rest of mapio's dependencies (google.cloud, mediapipe).
TIMEOUT = 20
PHRASE_TIME_LIMIT = 30
FINAL_SILENCE_DURATION = 3.0

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_DIR = os.path.join(HERE, "audio")
DEFAULT_BENCHMARK = os.path.join(HERE, "mapio_benchmark.json")


def input_devices() -> list[tuple[int | None, str]]:
    """Every capture device, system default first.

    Windows lists playback and capture in one table, so devices with no input
    channels are dropped -- picking one of those fails at open time with an
    error that does not say why.
    """
    devices: list[tuple[int | None, str]] = []
    audio = sr.Microphone.get_pyaudio().PyAudio()

    try:
        try:
            name = audio.get_default_input_device_info()["name"]
            devices.append((None, f"System default — {name}"))
        except Exception:
            devices.append((None, "System default"))

        for index, name in enumerate(sr.Microphone.list_microphone_names()):
            info = audio.get_device_info_by_index(index)
            if info.get("maxInputChannels", 0) > 0:
                devices.append((index, f"{index}: {name}"))
    finally:
        audio.terminate()

    return devices


def load_turns(benchmark_path: str) -> tuple[dict, list[dict]]:
    """(benchmark, flattened turns in recording order).

    Single-turn cases and multi-turn sessions both flatten to one entry per
    turn; each keeps a pointer back to its case so the manifest can be rebuilt
    with the original nesting.
    """
    with open(benchmark_path, encoding="utf-8") as f:
        bench = json.load(f)

    flat = []
    for case in bench["cases"]:
        turns = case.get("turns") or [case]
        for position, turn in enumerate(turns):
            flat.append({
                "case": case,
                "turn": turn,
                "id": turn.get("id", case["id"]),
                "position": position,
                "of": len(turns),
            })

    return bench, flat


def write_manifest(bench: dict, flat: list[dict], out_dir: str) -> int:
    """Rebuild manifest.json from whatever wavs exist. Returns turns written."""
    recorded = {}
    for entry in flat:
        wav_path = os.path.join(out_dir, f"{entry['id']}.wav")
        if not os.path.exists(wav_path):
            continue
        with wave.open(wav_path) as w:
            seconds = round(w.getnframes() / w.getframerate(), 2)
        recorded[entry["id"]] = {
            "wav": f"{entry['id']}.wav",
            "seconds": seconds,
            "recorded_at": datetime.fromtimestamp(
                os.path.getmtime(wav_path)
            ).isoformat(timespec="seconds"),
        }

    cases = []
    for case in bench["cases"]:
        turns = case.get("turns") or [case]
        kept = [
            dict(turn, audio=recorded[turn.get("id", case["id"])])
            for turn in turns
            if turn.get("id", case["id"]) in recorded
        ]
        if kept:
            cases.append(dict(case, turns=kept))

    manifest = {
        "$comment": (
            "Generated by benchmark/record_audio.py. Benchmark-shaped, holding "
            "only recorded turns. Turns keep their original utterance as the "
            "reference; run_parity_benchmark.py --audio-dir replaces it with "
            "the transcript, or sends the wav itself with --input audio. "
            "Sessions may be partial: skipped turns also skip their "
            "conversational state."
        ),
        "generated": datetime.now().isoformat(timespec="seconds"),
        "source_benchmark": os.path.relpath(DEFAULT_BENCHMARK, HERE),
        "cases": cases,
    }

    path = os.path.join(out_dir, "manifest.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump(manifest, f, indent=1)

    return len(recorded)


class Recorder:
    def __init__(self, root: tk.Tk, args, bench: dict, flat: list[dict]) -> None:
        self.root = root
        self.out_dir = args.dir
        self.server = args.server.rstrip("/") if args.server else ""
        self.bench = bench
        self.flat = flat
        self.cursor = 0
        self.busy = False

        self.recognizer = sr.Recognizer()
        self.recognizer.pause_threshold = FINAL_SILENCE_DURATION

        root.title("Record benchmark utterances")
        root.minsize(720, 0)
        frame = ttk.Frame(root, padding=16)
        frame.grid(sticky="nsew")
        root.columnconfigure(0, weight=1)
        frame.columnconfigure(0, weight=1)

        top = ttk.Frame(frame)
        top.grid(row=0, column=0, sticky="ew")
        top.columnconfigure(1, weight=1)
        ttk.Label(top, text="Input").grid(row=0, column=0, sticky="w")
        self.devices = input_devices()
        self.device = ttk.Combobox(
            top, state="readonly", values=[label for _, label in self.devices]
        )
        self.device.current(0)
        self.device.grid(row=0, column=1, sticky="ew", padx=(8, 0))

        self.heading = tk.StringVar()
        ttk.Label(frame, textvariable=self.heading, foreground="#666").grid(
            row=1, column=0, sticky="w", pady=(16, 4)
        )

        say_font = tkfont.nametofont("TkDefaultFont").copy()
        say_font.configure(size=say_font.cget("size") + 8)
        self.say = tk.StringVar()
        ttk.Label(
            frame, textvariable=self.say, font=say_font, wraplength=680, justify="left"
        ).grid(row=2, column=0, sticky="w")

        self.notes = tk.StringVar()
        ttk.Label(
            frame, textvariable=self.notes, foreground="#888", wraplength=680
        ).grid(row=3, column=0, sticky="w", pady=(8, 0))

        buttons = ttk.Frame(frame)
        buttons.grid(row=4, column=0, sticky="ew", pady=(20, 0))
        buttons.columnconfigure(1, weight=1)

        self.prev_button = ttk.Button(buttons, text="◀", width=4,
                                      command=lambda: self.move(-1))
        self.prev_button.grid(row=0, column=0)

        self.record_label = tk.StringVar(value="Record")
        self.record_button = ttk.Button(
            buttons, textvariable=self.record_label, command=self.toggle
        )
        self.record_button.grid(row=0, column=1, sticky="ew", padx=8, ipady=6)

        self.next_button = ttk.Button(buttons, text="▶", width=4,
                                      command=lambda: self.move(1))
        self.next_button.grid(row=0, column=2)

        self.status = tk.StringVar()
        ttk.Label(frame, textvariable=self.status, wraplength=680).grid(
            row=5, column=0, sticky="w", pady=(16, 0)
        )

        root.bind("<space>", lambda e: self.toggle())
        root.bind("<Left>", lambda e: self.move(-1))
        root.bind("<Right>", lambda e: self.move(1))

        # Start on the first turn with no recording, so resuming a session
        # picks up where it stopped rather than at the top.
        for i, entry in enumerate(self.flat):
            if not os.path.exists(self.wav_path(entry)):
                self.cursor = i
                break

        count = write_manifest(self.bench, self.flat, self.out_dir)
        self.status.set(f"{count} of {len(self.flat)} turns recorded — saving to {self.out_dir}")
        self.show()

    # -- state ------------------------------------------------------------- #

    def entry(self) -> dict:
        return self.flat[self.cursor]

    def wav_path(self, entry: dict) -> str:
        return os.path.join(self.out_dir, f"{entry['id']}.wav")

    def show(self) -> None:
        entry = self.entry()
        case, turn = entry["case"], entry["turn"]

        where = f"turn {entry['position'] + 1} of {entry['of']}" if entry["of"] > 1 else "single turn"
        done = "  ✓ recorded" if os.path.exists(self.wav_path(entry)) else ""
        self.heading.set(
            f"[{self.cursor + 1}/{len(self.flat)}]  {case['id']} · {entry['id']} · "
            f"{case['map']} · {where}{done}"
        )
        self.say.set(turn["utterance"])
        self.notes.set(turn.get("grading_notes", ""))

    def move(self, delta: int) -> None:
        if self.busy:
            return
        self.cursor = max(0, min(len(self.flat) - 1, self.cursor + delta))
        self.show()

    def set_status(self, text: str) -> None:
        self.root.after(0, self.status.set, text)

    # -- recording --------------------------------------------------------- #

    def toggle(self) -> None:
        if self.busy:
            # stop_listening() only clears a flag that listen() polls, so
            # calling it from the GUI thread while the worker blocks is safe.
            self.recognizer.stop_listening()
            self.set_status("stopping…")
            return

        entry = self.entry()
        path = self.wav_path(entry)
        if os.path.exists(path) and not messagebox.askyesno(
            "Record", f"{entry['id']}.wav exists. Replace it?"
        ):
            return

        self.busy = True
        self.record_label.set("Stop")
        for button in (self.prev_button, self.next_button):
            button.config(state="disabled")
        threading.Thread(target=self.__worker, args=(entry, path), daemon=True).start()

    def __worker(self, entry: dict, path: str) -> None:
        try:
            device = self.devices[self.device.current()][0]
            self.set_status(f"calibrating on {self.device.get()}")
            with sr.Microphone(device_index=device) as source:
                self.recognizer.adjust_for_ambient_noise(source)
                self.set_status(f"recording {entry['id']} — read the line, then pause or press Stop")
                audio = self.recognizer.listen(
                    source, timeout=TIMEOUT, phrase_time_limit=PHRASE_TIME_LIMIT
                )

            wav = audio.get_wav_data(convert_rate=16000, convert_width=2)
            if not wav:
                self.set_status("stopped — nothing recorded")
                return

            with open(path, "wb") as f:
                f.write(wav)

            seconds = len(wav) / (16000 * 2)
            count = write_manifest(self.bench, self.flat, self.out_dir)
            message = (f"saved {entry['id']}.wav ({seconds:.1f}s, {len(wav) // 1024} KB) — "
                       f"{count}/{len(self.flat)} recorded")

            if self.server:
                message += " | heard: " + self.__transcribe(wav)

            self.set_status(message)
            if self.cursor < len(self.flat) - 1:
                self.root.after(0, lambda: (setattr(self, "cursor", self.cursor + 1), self.show()))
        except sr.WaitTimeoutError:
            self.set_status("nothing heard — check the input device")
        except Exception as e:
            self.set_status(f"error: {e}")
        finally:
            self.busy = False
            self.root.after(0, self.__idle)

    def __idle(self) -> None:
        self.record_label.set("Record")
        for button in (self.prev_button, self.next_button):
            button.config(state="normal")
        self.show()

    def __transcribe(self, wav: bytes) -> str:
        body = json.dumps({"audio_b64": base64.b64encode(wav).decode(), "hints": []}).encode()
        request = urllib.request.Request(
            f"{self.server}/transcribe",
            data=body,
            headers={"Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(request, timeout=60) as resp:
                return repr(json.load(resp).get("text", ""))
        except Exception as e:
            return f"(transcribe failed: {e})"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dir", default=DEFAULT_DIR, help="where to write wavs")
    parser.add_argument("--benchmark", default=DEFAULT_BENCHMARK)
    parser.add_argument("--map", default=None, help="only turns for this map")
    parser.add_argument("--case", default=None, help="only turns for this case id")
    parser.add_argument(
        "--server",
        default="",
        help="transcription server, e.g. http://localhost:11435; "
        "when set, each recording is transcribed so you can hear-check it",
    )
    args = parser.parse_args()

    os.makedirs(args.dir, exist_ok=True)
    bench, flat = load_turns(args.benchmark)

    if args.map:
        flat = [e for e in flat if e["case"]["map"] == args.map]
    if args.case:
        flat = [e for e in flat if e["case"]["id"] == args.case]
    if not flat:
        raise SystemExit("No turns match the filter.")

    root = tk.Tk()
    Recorder(root, args, bench, flat)
    root.mainloop()


if __name__ == "__main__":
    main()
